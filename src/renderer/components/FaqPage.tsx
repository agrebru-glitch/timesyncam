import { useEffect, useRef } from 'react';
import { useApp } from '../App.tsx';

export function FaqPage() {
  const { state } = useApp();
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!state.faqAnchor || !ref.current) return;
    const el = ref.current.querySelector<HTMLElement>(`#faq-${state.faqAnchor}`);
    if (!el) return;
    el.scrollIntoView({ behavior: 'smooth', block: 'start' });
    el.classList.add('flash');
    const t = setTimeout(() => el.classList.remove('flash'), 1800);
    return () => clearTimeout(t);
  }, [state.faqAnchor]);

  return (
    <div className="page" ref={ref}>
      <div className="faq">
        <h1>Настройка камер</h1>
        <p className="lead">Пять минут перед съёмкой экономят часы на монтаже. Сначала — Sony, ниже — другие камеры.</p>

        <section id="faq-basics">
          <h2>Как программа понимает, когда снят клип</h2>
          <p>У каждого клипа программа ищет два источника времени:</p>
          <ul>
            <li><b>Часы камеры</b> — дата и время начала записи. Есть почти у всех камер, точность около секунды.</li>
            <li><b>Тайм-код</b> — счётчик кадров внутри файла. Если он идёт непрерывно (Free Run), паузы между клипами получаются точными до кадра, даже когда сам тайм-код не совпадает с реальным временем.</li>
          </ul>
          <p>Если тайм-код камеры синхронизирован с генератором или с другими камерами, такая камера становится <b>опорной</b>: остальные выравниваются по ней.</p>
        </section>

        <div className="group-title">Sony: A7 IV, A7S III, A7C II, A1, FX3, FX30 и другие</div>

        <section id="faq-clock">
          <h2>1. Выставьте часы на всех камерах</h2>
          <p>Одинаковые дата, время и часовой пояс, с точностью до секунды. Удобно выставлять по одному телефону: подготовьте время на минуту вперёд и подтвердите ровно в начале минуты.</p>
          <p>Меню: <span className="path">MENU → Настройка → Регион/дата/время</span>.</p>
          <p>Во время съёмки часы не трогайте. Если камера «забыла» дату после смены аккумулятора — значит, села внутренняя батарейка часов, поставьте камеру на зарядку.</p>
        </section>

        <section id="faq-tc-run">
          <h2>2. Тайм-код: Free Run</h2>
          <p><span className="path">MENU → Съёмка → TC/UB → Time Code Run → Free Run</span> (на старых моделях <span className="path">MENU → Настройка → Настройки TC/UB</span>).</p>
          <p>В режиме <b>Rec Run</b> тайм-код идёт только пока камера пишет, и паузы между клипами пропадают — программе придётся брать время с часов, точность упадёт до секунды.</p>
        </section>

        <section id="faq-tc-preset">
          <h2>3. Тайм-код: Preset и текущее время</h2>
          <p><span className="path">Time Code Make → Preset</span>. В режиме Regenerate тайм-код продолжается с последнего клипа на карте и ведёт себя как Rec Run.</p>
          <p><span className="path">Time Code Preset</span> — выставьте вручную примерно текущее время суток. Совпадать до кадра не обязательно: программа сама вычислит, на сколько тайм-код расходится с часами камеры. Зато так его удобно читать на монтаже.</p>
          <p>После обновления прошивки тайм-код сбрасывается — выставьте его снова.</p>
        </section>

        <section id="faq-ub">
          <h2>4. User Bit Time Rec — включить</h2>
          <p><span className="path">TC/UB → User Bit Time Rec → Вкл.</span> Камера дополнительно запишет время по часам. Это запасной источник на случай, если что-то пойдёт не так.</p>
        </section>

        <section id="faq-audio">
          <h2>5. Звук на каждой камере</h2>
          <p>Даже если основной звук пишется отдельно, держите встроенный микрофон камеры включённым и не убирайте уровень в ноль. По звуку легко найти общий момент на всех камерах.</p>
        </section>

        <section id="faq-manual-sync">
          <h2>6. Хлопок в начале — и точная подгонка в программе</h2>
          <p>В начале съёмки и после каждого перерыва сделайте хлопок или вспышку так, чтобы их видели все камеры. На монтаже:</p>
          <ul>
            <li>Переключитесь в «Мультивью» и поставьте курсор на хлопок.</li>
            <li>Стрелками ← → (по кадру, с Shift — по секунде) найдите кадр хлопка у опорной камеры.</li>
            <li>У камеры, которая расходится, нажимайте «−1 к» / «+1 к» в её карточке, пока хлопок не совпадёт. Сдвиг применяется ко всем клипам камеры сразу.</li>
          </ul>
          <p>На стадионе помните: звук идёт около 340 м/с. Если камеры стоят в 70 м друг от друга, звук придёт к ним с разницей примерно в 5 кадров. Поэтому точно подгоняйте по картинке: удар по мячу, вспышка, хлопок в кадре.</p>
        </section>

        <section id="faq-external-tc">
          <h2>7. Внешний тайм-код — опорная камера</h2>
          <p>FX3 (прошивка 2.00 и новее) и FX30 принимают тайм-код через кабель <b>VMC-BNCM1</b> от генератора (Tentacle Sync, Deity, RØDE Wireless PRO). У такой камеры тайм-код — это точное время, она становится опорной.</p>
          <p>Если программа не распознала это сама, в карточке камеры выберите «Тайм-код: точный — синхронизирован».</p>
          <p>Для A7 IV в справке Sony вход тайм-кода не упоминается. Для неё — часы, Free Run и хлопок.</p>
        </section>

        <section id="faq-proxy">
          <h2>8. Прокси — для быстрого предпросмотра</h2>
          <p><span className="path">MENU → Съёмка → Качество изображения → Настройки прокси → Прокси-запись: Вкл.</span>, формат <b>XAVC S HD</b> (H.264, 8 бит).</p>
          <p>Оригиналы 4:2:2 10-bit встроенный плеер не проигрывает, поэтому без прокси клипы показываются стоп-кадрами. При 100p и 120p камера прокси не пишет.</p>
        </section>

        <section id="faq-copy">
          <h2>9. Копируйте карту целиком</h2>
          <p>Вместе с файлами <span className="path">C0001M01.XML</span> рядом с клипами: в них Sony записывает время съёмки и тайм-код. Не переименовывайте клипы и не пересохраняйте их — иначе ломается связь с XML и прокси.</p>
          <p>Каждая камера — в свою папку. Несколько карт одной камеры можно перетащить на одну дорожку.</p>
        </section>

        <div className="group-title">Другие камеры</div>

        <section id="faq-other">
          <h2>Canon, Panasonic, Fujifilm, Nikon, Blackmagic</h2>
          <p>В меню тайм-кода выберите <b>Free Run</b> (свободный счёт) и выставьте тайм-код по текущему времени, если камера это умеет. Часы — по одному источнику, как для Sony. Камеры с входом тайм-кода подключайте к генератору — они станут опорными.</p>
          <h2 style={{ marginTop: 14 }}>GoPro, DJI, экшн-камеры</h2>
          <p>Время на них выставляется с телефона при подключении к приложению (GoPro Quik, DJI Fly / Mimo) — подключите каждую камеру перед съёмкой. GoPro и часть камер DJI пишут местное время с пометкой UTC; программа это учитывает. Если камера всё равно уехала на целые часы, во вкладке «Ошибки» будет кнопка сдвига.</p>
          <h2 style={{ marginTop: 14 }}>iPhone и Android</h2>
          <p>Часы телефонов сверяются с сетью и обычно точны. Приложения вроде Blackmagic Camera дополнительно пишут тайм-код.</p>
        </section>

        <section id="faq-recorders">
          <h2>Рекордеры звука</h2>
          <p>Zoom, Tascam, Sound Devices и другие пишут WAV с меткой времени (BWF). Перетащите папку рекордера на отдельную дорожку — он встанет по своему тайм-коду или часам. Выставьте на рекордере те же часы, что и на камерах.</p>
        </section>

        <section id="faq-raw">
          <h2>BRAW, R3D, Canon RAW, ARRIRAW</h2>
          <p>Эти форматы читаются только фирменными программами. Перегоните их в ProRes или H.264/H.265 с сохранением тайм-кода (например, в DaVinci Resolve) и добавьте полученные файлы.</p>
        </section>

        <section id="faq-import">
          <h2>Как открыть результат</h2>
          <ul>
            <li><b>DaVinci Resolve:</b> <span className="path">File → Import → Timeline…</span> и выберите сохранённый XML.</li>
            <li><b>Premiere Pro:</b> <span className="path">File → Import…</span> и выберите XML — появится секвенция с камерами на своих дорожках.</li>
          </ul>
          <p>Оригинальные файлы программа не меняет: в XML только ссылки на них и их места на таймлинии.</p>
        </section>

        <div className="group-title">О программе</div>
        <section id="faq-about">
          <h2>TimesynCam {__APP_VERSION__}</h2>
          <p>Разработчик — Andrey Grebenikov. Программа распространяется по лицензии GNU GPL версии 3: её можно свободно использовать, изучать и дорабатывать, сохраняя открытость кода.</p>
          <p>Для чтения видео используется FFmpeg (лицензия LGPL). Исходный код и релизы: <span className="path">github.com/agrebru-glitch/timesyncam</span>.</p>
        </section>
      </div>
    </div>
  );
}
